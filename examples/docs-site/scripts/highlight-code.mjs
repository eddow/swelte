// Build-time highlighter for the docs-site (Node only — never SSR/bundled).
//
// Imports `src/lib/snippets.ts`, highlights each `{ code, lang }` with shiki
// (`themes: { light: github-light, dark: github-dark }`, `defaultColor: false`
// so colors come purely from data-theme CSS vars), and writes
// `src/lib/snippets.gen.ts` exporting `codeHtml: Record<key, CodeSnippet>`.
//
// Run: `npm run highlight --workspace=examples/docs-site`
// (also wired into `predev`/`prebuild` so generated HTML is never stale).
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const libDir = join(here, '..', 'src', 'lib');

const { codeToHtml } = await import('shiki');

// snippets.ts is plain TS with no runtime deps — strip types with the
// TypeScript compiler already in devDependencies, then import the JS.
const { readFileSync } = await import('node:fs');
const { transpileModule } = await import('typescript');
const tsSrc = readFileSync(join(libDir, 'snippets.ts'), 'utf8');
const js = transpileModule(tsSrc, {
	compilerOptions: { module: 99 /* ESNext */, target: 99 /* ESNext */ }
}).outputText;
const dataUrl = `data:text/javascript;base64,${Buffer.from(js).toString('base64')}`;
const { snippets } = await import(dataUrl);

const keys = Object.keys(snippets).sort();
const out = {};
for (const key of keys) {
	const { code, lang } = snippets[key];
	const html = await codeToHtml(code, {
		lang,
		themes: { light: 'github-light', dark: 'github-dark' },
		defaultColor: false
	});
	// Strip the outer <pre><code> wrapper — Code.svelte owns the frame
	// (line numbers, title bar); keep inner token spans only.
	const inner = html
		.replace(/^<pre[^>]*><code>/, '')
		.replace(/<\/code><\/pre>\s*$/, '');
	out[key] = { html: inner, lang };
}

const outFile = join(libDir, 'snippets.gen.ts');
const body = `// GENERATED by scripts/highlight-code.mjs — do not edit.\n// Re-run: npm run highlight --workspace=examples/docs-site\nimport type { CodeSnippet } from './code.js';\n\nexport const codeHtml: Record<string, CodeSnippet> = ${JSON.stringify(out, null, '\t')};\n`;
mkdirSync(libDir, { recursive: true });
writeFileSync(outFile, body);
console.log(`[highlight-code] wrote ${outFile} (${keys.length} snippets)`);

