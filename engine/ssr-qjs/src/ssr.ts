// SSR manifest composer: reads `.swelte/ssr-manifest.json`
// (emitted by core, engine-agnostic) and composes `dist/ssr/render.js` —
// a single IIFE with no `node:` externals, no fetch, no top-level await.
//
// Entry shape: manifest { routes: [{ route, svelte, hasData }] } →
// render.js exports `renderRoute(route, props_json) -> { head, body }`
// (pure-sync: props in, HTML out). Compiled by the project's own
// `svelte()` plugin in SSR mode (`generate: 'server'`), so core never
// imports `svelte/compiler`.
//
// Guards (build errors with file+line):
// - `node:` / `node_modules` externals in route components
// - `fetch(` / top-level `await` in route components (QJS-compat rule:
//   JS stays pure-sync, load() lives in V)
export interface SsrComposeOptions {
	root: string
	outFile?: string
	dev?: boolean
}

export interface SsrManifest {
	version: 1
	hasError: boolean
	routes: { route: string; svelte: string; kind: string; hasData: boolean }[]
	error: string | null
	wrappers: string[]
}

export function composeRenderJs(manifest: SsrManifest, opts: SsrComposeOptions): string {
	const lines: string[] = [
		'// Auto-generated by @swelte/ssr-qjs from .swelte/ssr-manifest.json. Do not edit.',
		'// Single IIFE, no node: externals, no fetch, no top-level await (QJS-compat).',
		'(function (global) {',
		'"use strict";',
	]
	lines.push(`  var MANIFEST = ${JSON.stringify(manifest, null, 2).replace(/\n/g, '\n  ')};`)
	lines.push(`  var ROOT = ${JSON.stringify(opts.root)};`)
	for (const r of manifest.routes) {
		lines.push(`  // route ${r.route} <- ${r.svelte}${r.hasData ? ' (+data)' : ''}`)
	}
	if (manifest.error) lines.push(`  // error <- ${manifest.error}`)
	for (const w of manifest.wrappers) lines.push(`  // wrapper <- ${w}`)
	lines.push('')
	lines.push('  // Adapters fill this in: per-route compiled render fns keyed by')
	lines.push('  // manifest.route (route pattern → component, +route nesting via')
	lines.push('  // `children` snippet, global +error fallback). Placeholder keeps')
	lines.push('  // the dev disk-read bridge + HMR guard testable pre-compiler.')
	lines.push('  var RENDERERS = {};')
	lines.push('')
	lines.push('  function renderSvelteOnly(route) {')
	lines.push("    return { head: '', body: '<!--swelte:ssr:' + route + '-->' };")
	lines.push('  }')
	lines.push('')
	lines.push('  function renderRoute(route, props_json) {')
	lines.push('    var props = {};')
	lines.push('    try { props = JSON.parse(props_json || "{}"); } catch (e) { props = {}; }')
	lines.push('    void props;')
	lines.push('    if (RENDERERS[route]) {')
	lines.push('      try { return RENDERERS[route](props); } catch (e) { /* fall to +error */ }')
	lines.push('    }')
	lines.push('    if (MANIFEST.error) {')
	lines.push('      try {')
	lines.push('        var err = RENDERERS["/+error"];')
	lines.push('        if (err) return err({ status: 500, message: "render failed" });')
	lines.push('      } catch (e) { /* fall through */ }')
	lines.push('    }')
	lines.push('    return renderSvelteOnly(route);')
	lines.push('  }')
	lines.push('')
	lines.push('  global.renderRoute = renderRoute;')
	lines.push('  global.SWELTE_SSR_MANIFEST = MANIFEST;')
	lines.push('  return { renderRoute: renderRoute };')
	lines.push('})(typeof globalThis !== "undefined" ? globalThis : this);')
	return lines.join('\n') + '\n'
}

/** Build guard: reject node: externals, fetch, top-level await with file+line. */
export function assertQjsCompatible(file: string, src: string): void {
	const lines = src.split('\n')
	for (let i = 0; i < lines.length; i++) {
		const line = lines[i]
		if (/\bfrom\s+['"]node:/.test(line) || /\brequire\s*\(\s*['"]node:/.test(line)) {
			throw new Error(
				`[swelte:ssr-qjs] ${file}:${i + 1}: node: externals are forbidden in SSR render.js (QJS has no node:)`
			)
		}
		if (/(^|[^A-Za-z0-9_$])fetch\s*\(/.test(line)) {
			throw new Error(
				`[swelte:ssr-qjs] ${file}:${i + 1}: fetch() is forbidden in SSR components (QuickJS-compat: JS stays pure-sync, load() lives in V)`
			)
		}
	}
	if (/^\s*await\s+/m.test(src)) {
		const idx = lines.findIndex((l) => /^\s*await\s+/.test(l))
		throw new Error(
			`[swelte:ssr-qjs] ${file}:${idx + 1}: top-level await is forbidden in SSR render.js (QuickJS-compat: pure-sync renderer)`
		)
	}
}
