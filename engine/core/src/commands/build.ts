// `swelte build`: typecheck -> generate -> `vite build` -> `v -o` server binary.
// The V binary serves dist/ + API (single artifact, no Node at runtime).
// Roadmap §6: prod WASM bundle compiles in the plugin's generateBundle
// hook (`v -b wasm -os browser` → dist/assets/app_lib-*.wasm, exactly
// one *.wasm in dist/assets/ — the [swelte] log line proves it).
// Cross-build: `swelte build --target-os <os>` (linux|macos|windows,
// also SWELTE_TARGET_OS / swelte.targetOs) passes `-os <os>` to the
// `v -o` link; smoke probe + prerender crawl skip (foreign binary can't
// boot — assert artifacts only). WASM untouched (always `-os browser`);
// QJS embed fails fast unless a per-OS libqjs-<os>.a exists.
import { execFileSync } from 'node:child_process'
import { existsSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import type { Ctx } from './types.js'
import { killPort, portFree, probeSmoke, takePort, waitPort } from './dev.js'

// Deploy-target shims (docs (built) item 4): packaging only, no
// Node runtime. `static` = pure `dist/` (no server consumer); `node` =
// Dockerfile-style host snippet; `edge` = `_headers`-style CDN file;
// `auto` (default) = no extra files. Single artifact `dist/server` +
// `dist/` holds in every mode.
export function writeTargetShim(
	root: string,
	distDir: string,
	target: string,
	isrHeaders: Record<string, string>,
	log: (m: string) => void
): void {
	if (target === 'static') {
		writeFileSync(join(root, distDir, '.swelte-static'), 'static\n')
		log('target static: dist/ only (no server consumer)')
		return
	}
	if (target === 'node') {
		writeFileSync(
			join(root, distDir, 'Dockerfile.swelte'),
			`# Auto-generated by swelte (target: node). No Node runtime - runs dist/server.\nFROM debian:stable-slim\nWORKDIR /app\nCOPY . .\nEXPOSE 8131\nENV PORT=8131 SWELTE_DIST=dist\nCMD [\"./dist/server\"]\n`
		)
		log('target node: dist/Dockerfile.swelte (+ dist/server)')
		return
	}
	if (target === 'edge') {
		const lines = ['/*', '  X-Swelte-Target: edge', '']
		for (const [prefix, seconds] of Object.entries(isrHeaders)) {
			lines.push(`${prefix === '/' ? '/*' : `${prefix}/*`}`, `  Cache-Control: public, max-age=0, s-maxage=${seconds}`, '')
		}
		writeFileSync(join(root, distDir, '_headers'), lines.join('\n'))
		log('target edge: dist/_headers')
		return
	}
}

function listDevWasm(root: string): string[] {
	try {
		const devDir = join(root, '.swelte', 'dev')
		const out: string[] = []
		const walk = (dir: string) => {
			for (const e of readdirSync(dir, { withFileTypes: true })) {
				const q = join(dir, e.name)
				if (e.isDirectory()) {
					walk(q)
					continue
				}
				if (e.name.endsWith('.wasm')) out.push(q + ' (' + statSync(q).size + 'B)')
			}
		}
		walk(devDir)
		return out.length > 0 ? ['wasm dev: ' + out.join(', ')] : ['wasm dev: (no #lib/ modules)']
	} catch {
		return ['wasm dev: (no #lib/ modules)']
	}
}

export async function runBuild(ctx: Ctx): Promise<void> {
	const root = resolve(String(ctx.opts.root ?? process.cwd()))
	const outBinary = String(ctx.opts.output ?? join(root, 'dist', 'server'))
	const targetFlag = String(ctx.opts.target ?? '').toLowerCase()
	let targetIsrHeaders: Record<string, string> = {}
	const { resolveV, vVersion, toolchainEnv, resolveCC, resolveTargetOs, hostTargetOs, vOsArgs } =
		await import('../toolchain.js')
	const { loadConfig } = await import('../gen/config.js')
	const v = resolveV(import.meta.url)
	ctx.log(`V toolchain: ${vVersion(v)} (${v})`)
	ctx.log(`root ${root}`)
	const cfg = await loadConfig(root)
	const genAbs = join(root, cfg.outDir)
	// Cross-build OS (build-only): CLI wins, SWELTE_TARGET_OS middle,
	// `swelte.targetOs` config last. Host-native = '' (no -os flag).
	// WASM untouched: plugin always uses `-os browser`. dev/preview/test
	// stay host-native (this flag is build-only).
	const crossOs = ctx.opts['target-os'] ?? ctx.opts.targetOs
	const targetOs = resolveTargetOs({ cli: crossOs, config: cfg.targetOs })
	const cross = targetOs !== ''
	if (cross) {
		ctx.log(`target OS: ${targetOs} (host ${hostTargetOs()} — smoke probe skipped, artifacts only)`)
		// Forward to adapter generateBundle passes (QJS link): env wins in
		// the precedence chain, so publish the resolved OS for any
		// downstream reader that only sees env.
		process.env.SWELTE_TARGET_OS = targetOs
	}
	// Item pass-through: build env for the smoke probe — config knobs
	// become env when not already set (same env-wins rule as §11).
	if (!process.env.SWELTE_TRAILING_SLASH && cfg.trailingSlash !== 'ignore')
		process.env.SWELTE_TRAILING_SLASH = cfg.trailingSlash
	if (!process.env.SWELTE_CSRF_CHECK_ORIGIN && cfg.csrf === 'enforce')
		process.env.SWELTE_CSRF_CHECK_ORIGIN = '1'
	if (!process.env.SWELTE_METHOD_OVERRIDE && cfg.methodOverride) process.env.SWELTE_METHOD_OVERRIDE = '1'
	if (!process.env.SWELTE_VERSION && cfg.version !== '') process.env.SWELTE_VERSION = cfg.version
	// ISR lite: freeze the `isr` map into SWELTE_ISR for the prerender
	// crawl + smoke probe env (the V binary reads it per request).
	if (!process.env.SWELTE_ISR && Object.keys(cfg.isr).length > 0)
		process.env.SWELTE_ISR = Object.entries(cfg.isr)
			.map(([k, v]) => `${k}=${v}`)
			.join(',')
	// 1. generate into .swelte/ (routes/*.v + server_gen.v + .swelte/server.v harness).
	try {
		const mod = (await import('../vite.js')) as unknown as {
			default?: (opts: Record<string, unknown>) => unknown
			swelte?: (opts: Record<string, unknown>) => unknown
		}
		const swelte = mod.default ?? mod.swelte
		if (typeof swelte !== 'function') throw new Error('vite.js has no swelte export')
		const plug = swelte({}) as unknown as {
			buildStart?: () => Promise<void> | void
			configResolved?: (c: { root: string }) => void
		}
		plug.configResolved?.({ root })
		await plug.buildStart?.()
		ctx.log('generated .swelte/')
	} catch (e) {
		throw new Error(`codegen failed: ${(e as Error).message}`)
	}
	// Single `v -o`: it typechecks as it compiles (0.5.2 has no `v check`).
	// The old flow ran a throwaway typecheck compile first — same errors,
	// double the slowest step. Target the harness FILE (`.swelte/server.v`):
	// V resolves `routes/` relative to it (targeting the dir fails — V
	// skips dotted dirs).
	// 2. WASM (roadmap §6): compiled live by the plugin - the generate()
	// above emits .swelte/dev/<mod>.wasm per file (mtime-guarded); the
	// prod bundle compiles in generateBundle during vite build below.
	for (const line of listDevWasm(root)) ctx.log(line)
	// 3. vite build FIRST (it wipes dist/, incl. any binary inside it).
	// (Adapter generateBundle emits dist/ssr/render.js + the QJS bridge
	// here when the project uses @swelte/ssr-qjs — the smoke in step 5
	// picks it up.)
	try {
		execFileSync('npx', ['vite', 'build'], { cwd: root, encoding: 'utf8', env: toolchainEnv() })
	} catch (e) {
		const err = e as { stderr?: Buffer; stdout?: Buffer; message?: string }
		throw new Error(
			`vite build failed:\n${err.stderr?.toString() ?? err.stdout?.toString() ?? err.message}`
		)
	}
	ctx.log('vite build: ok')
	// 3b. QJS prod link, second generate pass (adapter-owned): the bridge
	// (routes/swelte_qjs_bridge.v) did not exist during step 1 (it is
	// emitted by generateBundle above) — regenerate so server_gen.v +
	// .swelte/server.v compile against it. Core-only projects: generate() is
	// idempotent, no bridge, no QJS. Then rebuild libqjs.a (mtime-guarded).
	try {
		const mod = (await import('../vite.js')) as unknown as {
			default?: (opts: Record<string, unknown>) => unknown
			swelte?: (opts: Record<string, unknown>) => unknown
		}
		const swelte = mod.default ?? mod.swelte
		if (typeof swelte !== 'function') throw new Error('vite.js has no swelte export')
		const plug = swelte({}) as unknown as {
			buildStart?: () => Promise<void> | void
			configResolved?: (c: { root: string }) => void
		}
		plug.configResolved?.({ root })
		await plug.buildStart?.()
		ctx.log('regenerated .swelte/ (QJS bridge pass)')
	} catch (e) {
		throw new Error(`codegen (QJS pass) failed: ${(e as Error).message}`)
	}
	// 4. `v -o` the server binary into dist/ AFTER the wipe (dist-adjacent,
	// never the project root). Target the harness file (see typecheck).
	// QJS projects need -enable-globals (bridge cache) + system cc (V's
	// bundled tcc cannot compile quickjs.c — but we link the prebuilt
	// .a, so any cc works; gcc preferred).
	// Conda-safe: absolute cc path + conda-free PATH (conda's ld shadows
	// the system linker and breaks every V C-link step).
	// Detect: bridge file present → QJS flags.
	let vExtra: string[] = []
	try {
		const { existsSync } = await import('node:fs')
		if (existsSync(join(genAbs, 'routes', 'swelte_qjs_bridge.v'))) {
			// QJS embed is the hard part of cross-build: libqjs.a is
			// prebuilt for the HOST. Needs per-OS prebuilt
			// (libqjs-<os>.a) or from-source compile under the target
			// cc. A host-prebuilt archive silently links the wrong ABI,
			// so cross + bridge = fail fast. Core-only projects cross
			// trivially today. The adapter publishes per-OS archives as
			// `.swelte/qjs/libqjs-<os>.a` (bridge `#flag`s that name);
			// until then this guard stays.
			if (cross && !existsSync(join(genAbs, 'qjs', `libqjs-${targetOs}.a`))) {
				throw new Error(
					`cross-build --target-os ${targetOs} with QJS embed: no per-OS archive at .swelte/qjs/libqjs-${targetOs}.a ` +
						`(only the host-prebuilt libqjs.a exists, which would link the wrong ABI). ` +
						`Remove the SSR bridge for a core-only cross, or rebuild libqjs.a under the target cc.`
				)
			}
			vExtra = ['-enable-globals', '-cc', resolveCC()]
			ctx.log(`QJS embed: -enable-globals -cc ${vExtra[vExtra.length - 1]} (bridge present)`)
		}
	} catch (e) {
		/* core-only — unless it's our cross guard above */
		if ((e as Error).message?.includes('cross-build --target-os')) throw e
	}
	try {
		execFileSync(v, [...vOsArgs(targetOs), '-o', outBinary, ...vExtra, join(genAbs, 'server.v')], {
			cwd: root,
			stdio: ['ignore', 'pipe', 'pipe'],
			env: toolchainEnv(),
		})
	} catch (e) {
		const err = e as { stderr?: Buffer; stdout?: Buffer; message?: string }
		throw new Error(
			`v -o failed: ${err.stderr?.toString() ?? err.stdout?.toString() ?? err.message}` +
				`\n(hint: conda on PATH ships a conflicting ld — build strips conda dirs; if this persists, run with a clean PATH or conda deactivate)`
		)
	}
	ctx.log(`V binary: ${outBinary}`)
	// 4b. Prerender/SSG crawl (docs (built) item 3): additive
	// `dist/*.html` only. Boots the built binary on an ephemeral port,
	// GETs each crawl URL with browser Accept, writes 200 HTML to
	// `dist/<route>/index.html` (root → `dist/index.html` stays the shell).
	// Runtime/SPA-first defaults unchanged; probes/JSON untouched.
	// Cross-build: the foreign binary can't boot on this host — skip the
	// crawl (assert artifacts only), like the smoke probe below.
	if (cross) {
		ctx.log('prerender: skipped (cross-build target != host — foreign binary cannot boot)')
	} else {
		try {
			const { runPrerender } = await import('./prerender.js')
			await runPrerender(root, outBinary, cfg as unknown as Record<string, unknown>, {
				log: ctx.log,
				onIsrHeaders: (headers) => {
					targetIsrHeaders = headers
				},
			})
		} catch (e) {
			throw new Error(`prerender failed: ${(e as Error).message}`)
		}
	}
	// 5. Smoke: boot the binary, probe page + API, stop. Engine-agnostic:
	// static shell + JSON only. SSR HTML is the adapter's proof (its own
	// check boots the sidecar + asserts markers) — core never imports or
	// starts an engine. If SWELTE_SSR_URL happens to be set in the env,
	// Hand will proxy (its contract), but core sets nothing.
	// Cross-build: foreign binary can't boot — assert artifacts only.
	if (cross) {
		ctx.log(`build done: ${outBinary} + dist/ (cross ${targetOs}, smoke skipped)`)
	} else {
		const probePort = takePort(ctx.opts.port, 4173)
		await killPort(probePort, ctx.log)
		const hasGreetRoute =
			existsSync(join(root, cfg.routesDir, 'api', 'greet.v')) ||
			existsSync(join(root, cfg.routesDir, 'api', 'greet', '+page.v')) ||
			existsSync(join(root, cfg.routesDir, 'api', 'greet', 'index.v'))
		const child = (await import('node:child_process')).spawn(outBinary, [], {
			cwd: root,
			env: {
				...process.env,
				PORT: String(probePort),
				SWELTE_DIST: 'dist',
			},
			stdio: ['ignore', 'pipe', 'pipe'],
		})
		let logged = ''
		child.on('error', (e: Error) => {
			logged += `\nspawn failed: ${(e as Error).message}`
		})
		child.stderr?.on('data', (d: Buffer) => {
			logged += d.toString()
		})
		child.stdout?.on('data', (d: Buffer) => {
			logged += d.toString()
		})
		try {
			try {
				await probeSmoke(probePort, hasGreetRoute, ctx.log)
			} catch (e) {
				throw new Error(`${(e as Error).message}\n${logged}`)
			}
		} finally {
			try {
				child.kill('SIGTERM')
			} catch {
				/* ignore */
			}
			await new Promise((r) => setTimeout(r, 800))
			try {
				child.kill('SIGKILL')
			} catch {
				/* ignore */
			}
			// Best-effort port cleanup (Linux-only tool — skip elsewhere).
			await killPort(probePort, () => {})
		}
		ctx.log(`build done: ${outBinary} + dist/`)
	}
	// 6. Target shim (packaging only): `--target` flag wins, else config.
	writeTargetShim(
		root,
		cfg.distDir,
		targetFlag === 'static' || targetFlag === 'node' || targetFlag === 'edge' ? targetFlag : cfg.target,
		targetIsrHeaders,
		ctx.log
	)
}
