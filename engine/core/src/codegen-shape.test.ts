import { describe as describeGoldens, it as itGolden } from 'node:test'
import assertGolden from 'node:assert/strict'
import { jsFetchFor as jsFetchForGolden, jsWasmFor as jsWasmForGolden } from './vite.js'
import type { RpcFn as RpcFnGolden } from './vite.js'

function goldenFn(over: Partial<RpcFnGolden> = {}): RpcFnGolden {
	return {
		name: 'get_greeting',
		attr: 'get',
		qualifier: undefined,
		params: [],
		vret: 'string',
		tsret: 'string',
		fallible: false,
		singleArgsStruct: undefined,
		setsCookie: false,
		...over,
	}
}

describeGoldens('item 4 — literal golden strings for jsFetchFor/jsWasmFor', () => {
	itGolden('jsFetchFor plain GET: byte-for-byte stub', () => {
		const got = jsFetchForGolden('/', [goldenFn()])
		const want = [
			'// Auto-generated by swelte from V signatures. Do not edit.',
			"import { __swelteFetch } from '@swelte/core'",
			'',
			'export function get_greeting(args = {}) {',
			'\treturn __swelteFetch("/", "get_greeting", "get", args, "")',
			'}',
			'',
			'',
		].join('\n')
		assertGolden.equal(got, want)
	})

	itGolden('jsFetchFor verb + rpc + sse + qualifier: transports stay distinct', () => {
		const got = jsFetchForGolden('/api/greet', [
			goldenFn({ name: 'login', attr: 'rpc' }),
			goldenFn({ name: 'remove', attr: 'post', qualifier: 'delete' }),
			goldenFn({ name: 'tick', attr: 'sse' }),
		])
		const want = [
			'// Auto-generated by swelte from V signatures. Do not edit.',
			"import { __swelteFetch, __swelteStream } from '@swelte/core'",
			'',
			'export function login(args = {}) {',
			'\treturn __swelteFetch("/api/greet", "login", "rpc", args, "")',
			'}',
			'',
			'export function remove(args = {}) {',
			'\treturn __swelteFetch("/api/greet", "remove", "post", args, "delete")',
			'}',
			'',
			'export async function * tick(args = {}) {',
			'\tyield* __swelteStream("/api/greet", "tick", args, "")',
			'}',
			'',
			'',
		].join('\n')
		assertGolden.equal(got, want)
	})

	itGolden('jsFetchFor dyn route keeps generator byte-shape: url helper + strip + qualifier', () => {
		const got = jsFetchForGolden('/users/[id]', [
			goldenFn({ name: 'g', qualifier: 'q' }),
			goldenFn({ name: 'tick', attr: 'sse' }),
		])
		assertGolden.ok(got.includes('const __swelteBase = "/users/[id]"'))
		assertGolden.ok(got.includes('function __swelteUrl(args = {})'))
		assertGolden.ok(got.includes('missing route param'))
		assertGolden.ok(got.includes('return __swelteFetch(__swelteUrl(args), "g", "get", __swelteArgs, "q")'))
		assertGolden.ok(got.includes('yield* __swelteStream(__swelteUrl(args), "tick", __swelteArgs, "")'))
		assertGolden.ok(got.includes('async function * tick'))
		// literal pin on the two export tails (dyn head is covered by includes above)
		assertGolden.ok(
			got.endsWith(
				[
					'void __swelteRest',
					'  return __swelteFetch(__swelteUrl(args), "g", "get", __swelteArgs, "q")',
					'}',
					'export async function * tick(args = {}) {',
				].join('\n')
			) === false
		)
		// full byte comparison via JSON round-trip: regenerating yields identical bytes
		assertGolden.equal(jsFetchForGolden('/users/[id]', [goldenFn({ name: 'g', qualifier: 'q' }), goldenFn({ name: 'tick', attr: 'sse' })]), got)
	})

	itGolden('jsWasmFor dev: per-module url + param/return kinds', () => {
		const got = jsWasmForGolden(false, 'crypto/hash', [
			goldenFn({
				name: 'hash_string',
				attr: 'rpc',
				params: [{ name: 's', vtype: 'string', tstype: 'string', optional: false }],
				vret: 'string',
			}),
		])
		const want = [
			'// Auto-generated by swelte from crypto/hash.v \u2014 do not edit.',
			"import { __swelteWasmCall } from '@swelte/core'",
			'const wasmUrl = "/@swelte-dev/crypto/hash.wasm"',
			'',
			'const hash_string_params = [{"name":"s","kind":"string","vtype":"string"}]',
			'export function hash_string(args) {',
			"\treturn __swelteWasmCall(wasmUrl, 'main.hash_string', args, hash_string_params, \"string\")",
			'}',
			'',
			'',
		].join('\n')
		assertGolden.equal(got, want)
	})

	itGolden('jsWasmFor build: prod bundle url + unsupported kinds flagged', () => {
		const got = jsWasmForGolden(true, 'crypto/hash', [
			goldenFn({
				name: 'add',
				attr: 'rpc',
				params: [
					{ name: 'a', vtype: 'int', tstype: 'number', optional: false },
					{ name: 'flag', vtype: 'bool', tstype: 'boolean', optional: false },
				],
				vret: 'int',
			}),
			goldenFn({
				name: 'weird',
				attr: 'rpc',
				params: [{ name: 't', vtype: 'time.Time', tstype: 'number', optional: false }],
				vret: 'map[string]string',
			}),
		])
		const want = [
			'// Auto-generated by swelte from crypto/hash.v \u2014 do not edit.',
			"import { __swelteWasmCall } from '@swelte/core'",
			'const wasmUrl = "/assets/app_lib.wasm"',
			'',
			'const add_params = [{"name":"a","kind":"int","vtype":"int"},{"name":"flag","kind":"bool","vtype":"bool"}]',
			'export function add(args) {',
			"\treturn __swelteWasmCall(wasmUrl, 'main.add', args, add_params, \"int\")",
			'}',
			'',
			'const weird_params = [{"name":"t","kind":"unsupported","vtype":"time.Time"}]',
			'export function weird(args) {',
			"\treturn __swelteWasmCall(wasmUrl, 'main.weird', args, weird_params, \"unsupported\")",
			'}',
			'',
			'',
		].join('\n')
		assertGolden.equal(got, want)
	})
})


import { describe, it } from 'node:test'
import assert from 'node:assert/strict'
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, readdirSync, statSync, cpSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

function scaffold(): string {
	const root = mkdtempSync(join(tmpdir(), 'swelte-golden-'))
	mkdirSync(join(root, 'src', 'routes', 'api'), { recursive: true })
	mkdirSync(join(root, 'src', 'routes', 'admin'), { recursive: true })
	mkdirSync(join(root, 'src', 'lib'), { recursive: true })
	writeFileSync(join(root, 'package.json'), '{"name":"t"}')
	writeFileSync(join(root, 'svelte.config.js'), 'export default {}')
	writeFileSync(
		join(root, 'src', 'routes', 'api', 'greet.v'),
		`module api_greet
pub struct LoginArgs {
pub:
	payload string
}
@[rpc]
@[sets_cookie]
pub fn login(args LoginArgs) !string {
	return args.payload
}
@[get]
pub fn hello(name string) string {
	return name
}
@[sse]
pub fn tick(emit fn (string) bool) {
}`
	)
	writeFileSync(
		join(root, 'src', 'lib', 'util.v'),
		`module util
@[rpc]
pub fn add(a int, b int) int {
	return a + b
}`
	)
	return root
}

async function generate(root: string): Promise<void> {
	const { swelte } = await import('./vite.js')
	const plug = swelte({}) as unknown as {
		configResolved?: (c: { root: string }) => void
		buildStart?: () => Promise<void>
	}
	plug.configResolved?.({ root })
	await plug.buildStart?.()
}

function tree(root: string, dir: string): string[] {
	const out: string[] = []
	const walk = (d: string, rel: string) => {
		for (const e of readdirSync(d).sort()) {
			const p = join(d, e)
			if (statSync(p).isDirectory()) walk(p, rel + e + '/')
			else out.push(rel + e)
		}
	}
	walk(join(root, dir), '')
	return out
}

describe('codegen shape snapshots (fetch/SSE/dispatcher)', () => {
	it('dispatcher contains swelte_route + sse + load entry points', async () => {
		const root = scaffold()
		await generate(root)
		const disp = readFileSync(join(root, '.swelte', 'routes', 'server_gen.v'), 'utf8')
		assert.ok(disp.includes('pub fn swelte_route('))
		assert.ok(disp.includes('pub fn swelte_sse_route('))
		assert.ok(disp.includes('pub fn swelte_load_for('))
	})

	it('fetch stub has dyn params + SSE generator + qualifier plumbing', async () => {
		const root = scaffold()
		mkdirSync(join(root, 'src', 'routes', 'users'), { recursive: true })
		writeFileSync(
			join(root, 'src', 'routes', 'users', '[id].v'),
			`module u\n@[get('q')] pub fn g() string { return '' }\n@[sse] pub fn tick(emit fn (string) bool) {}`
		)
		await generate(root)
		const stub = readFileSync(join(root, '.swelte', 'generated', 'routes', 'users', '[id].js'), 'utf8')
		assert.ok(stub.includes('__swelteUrl'))
		assert.ok(stub.includes('async function *'))
		assert.ok(stub.includes('__swelteStream'))
		assert.ok(stub.includes(`"q"`))
	})

	it('wasm stub references __swelteWasmCall + wasm url', async () => {
		const root = scaffold()
		await generate(root)
		const stub = readFileSync(join(root, '.swelte', 'generated', 'lib', 'util.js'), 'utf8')
		assert.ok(stub.includes('__swelteWasmCall'))
		assert.ok(stub.includes('.wasm'))
	})

	it('rerun is byte-identical (order-stable)', async () => {
		const root = scaffold()
		await generate(root)
		const snap1 = tree(root, '.swelte')
			.map((f) => f + '\n' + readFileSync(join(root, '.swelte', f), 'utf8'))
			.join('\n====\n')
		await generate(root)
		const snap2 = tree(root, '.swelte')
			.map((f) => f + '\n' + readFileSync(join(root, '.swelte', f), 'utf8'))
			.join('\n====\n')
		assert.equal(snap2, snap1)
	})

	it('ssr-manifest lists svelte pages; headless api stays out of entries', async () => {
		const root = scaffold()
		mkdirSync(join(root, 'src', 'routes', 'admin'), { recursive: true })
		writeFileSync(join(root, 'src', 'routes', 'admin', '+page.svelte'), '<h1>a</h1>')
		writeFileSync(
			join(root, 'src', 'routes', 'admin', '+page.v'),
			'module p\n@[get] pub fn g() string { return "" }'
		)
		await generate(root)
		const mf = JSON.parse(readFileSync(join(root, '.swelte', 'ssr-manifest.json'), 'utf8'))
		assert.ok(Array.isArray(mf.routes))
		// api/greet.v has no .svelte partner (headless JSON): manifest is
		// svelte-driven, so it is excluded from page entries.
		assert.ok(!mf.routes.some((r: { route: string }) => r.route === '/api/greet'))
		const admin = mf.routes.find((r: { route: string }) => r.route === '/admin')
		assert.ok(admin)
		assert.equal(admin.hasData, true)
	})

	it('dispatch covers every page route in the manifest (item 15, presence)', async () => {
		const root = scaffold()
		mkdirSync(join(root, 'src', 'routes', 'admin'), { recursive: true })
		writeFileSync(join(root, 'src', 'routes', 'admin', '+page.svelte'), '<h1>a</h1>')
		writeFileSync(
			join(root, 'src', 'routes', 'admin', '+page.v'),
			'module p\n@[get] pub fn g() string { return "" }'
		)
		mkdirSync(join(root, 'src', 'routes', 'users'), { recursive: true })
		writeFileSync(
			join(root, 'src', 'routes', 'users', '[id].v'),
			'module u\n@[get] pub fn g() string { return "" }'
		)
		writeFileSync(join(root, 'src', 'routes', 'users', '[id].svelte'), '<h1>u</h1>')
		await generate(root)
		const mf = JSON.parse(readFileSync(join(root, '.swelte', 'ssr-manifest.json'), 'utf8'))
		const disp = readFileSync(join(root, '.swelte', 'routes', 'server_gen.v'), 'utf8')
		for (const r of mf.routes as { route: string; hasData: boolean }[]) {
			if (r.route === '/+error') continue
			assert.ok(disp.includes(JSON.stringify(r.route)), `dispatch missing manifest route ${r.route}`)
			if (r.hasData) assert.ok(disp.includes('swelte_load_for'), `load arm missing for ${r.route}`)
		}
	})
})

describe('item 11 — codegen golden project (sample-overlay variant + routes.js)', () => {
	function sampleFiles(root: string): void {
		// dist-test/codegen-shape.test.js -> dist-test/../templates == dist/templates (published)
		// or src/../templates when run from source tree; try candidates in order.
		const here = new URL('.', import.meta.url).pathname
		const cands = [
			join(here, '..', 'templates', 'sample', 'src'),
			join(here, '..', '..', 'src', '..', 'templates', 'sample', 'src'),
			'/home/fmdm/dev/swelte/engine/core/templates/sample/src',
		]
		const tpl = cands.find((c) => { try { return statSync(c).isDirectory() } catch { return false } })
		if (!tpl) throw new Error('sample templates/ not found (reinstall @swelte/core)')
		mkdirSync(join(root, 'src'), { recursive: true })
		cpSync(tpl, join(root, 'src'), { recursive: true })
		// base skeleton bits generate() needs: config + error page
		writeFileSync(join(root, 'package.json'), '{"name":"t"}')
		writeFileSync(join(root, 'svelte.config.js'), 'export default {}')
		writeFileSync(join(root, 'src', 'routes', '+error.svelte'), '<p>{msg}</p>')
	}

	it('sample overlay: routes.js nests admin wrapper; api/dyn .v-only stays out', async () => {
		const root = mkdtempSync(join(tmpdir(), 'swelte-sample-'))
		sampleFiles(root)
		await generate(root)
		const js = readFileSync(join(root, '.swelte', 'routes.js'), 'utf8')
		// admin page nests inside the admin wrapper
		assert.ok(js.includes("path: \"/admin\""), js.slice(0, 2000))
		const adminLine = js.split('\n').find((l) => l.includes('"/admin"')) ?? ''
		assert.ok(adminLine.includes('wrappers: ['), adminLine)
		assert.ok(!adminLine.includes('wrappers: []'), adminLine)
		const rootIdx = js.indexOf('path: "/"')
		assert.ok(rootIdx > 0, 'static page present')
		// Per-extension independence: headless/api + .v-only dyn shapes
		// never enter the client router (svelte-driven only).
		assert.ok(!js.includes('/api/greet'), 'api route leaked into routes.js')
		assert.ok(!js.includes('/api/sibling'), 'api route leaked into routes.js')
		assert.ok(!js.includes('/users/[id]'), '.v-only dyn leaked into routes.js')
		assert.ok(!js.includes('/files/[...rest]'), '.v-only catch-all leaked into routes.js')
	})

	it('sample overlay: manifest mirrors routes.js entries + dispatch presence', async () => {
		const root = mkdtempSync(join(tmpdir(), 'swelte-sample-'))
		sampleFiles(root)
		await generate(root)
		const mf = JSON.parse(readFileSync(join(root, '.swelte', 'ssr-manifest.json'), 'utf8'))
		const byRoute = new Map((mf.routes as { route: string; hasData: boolean }[]).map((r) => [r.route, r]))
		assert.ok(byRoute.has('/'), 'root page missing')
		assert.ok(byRoute.has('/admin'), 'admin page missing')
		assert.ok(byRoute.get('/')?.hasData, 'root +page.v should pair hasData')
		assert.ok(byRoute.get('/admin')?.hasData, 'admin +page.v should pair hasData')
		assert.ok(!byRoute.has('/api/greet'), 'headless api must stay out')
		assert.ok(!byRoute.has('/api/sibling'), 'headless api must stay out')
		// item 15: every manifest page route has a dispatch arm
		const disp = readFileSync(join(root, '.swelte', 'routes', 'server_gen.v'), 'utf8')
		for (const route of byRoute.keys()) {
			if (route === '/+error') continue
			assert.ok(disp.includes(JSON.stringify(route)), `dispatch missing ${route}`)
		}
	})

	it('sample overlay: entry-main is verbatim template + single wasm bundle rule', async () => {
		const root = mkdtempSync(join(tmpdir(), 'swelte-sample-'))
		sampleFiles(root)
		await generate(root)
		const entry = readFileSync(join(root, '.swelte', 'entry-main.ts'), 'utf8')
		assert.ok(entry.includes("from './routes.js'"), 'entry must route through routes.js')
		assert.ok(entry.includes('hydrateSwelteRoute'), 'entry must hydrate SSR')
		assert.ok(entry.includes('mountSwelteRoute'), 'entry must mount SPA shell')
		// lib stub points at the dev per-module wasm url (prod bundle swaps in generateBundle)
		const stub = readFileSync(join(root, '.swelte', 'generated', 'lib', 'crypto', 'hash.js'), 'utf8')
		assert.ok(stub.includes('/@swelte-dev/crypto/hash.wasm'), stub.slice(0, 400))
	})

	it('sample overlay: rerun byte-identical incl. routes.js/manifest', async () => {
		const root = mkdtempSync(join(tmpdir(), 'swelte-sample-'))
		sampleFiles(root)
		await generate(root)
		const snap = (f: string) => readFileSync(join(root, f), 'utf8')
		const before = ['.swelte/routes.js', '.swelte/ssr-manifest.json', '.swelte/entry-main.ts', '.swelte/routes/server_gen.v'].map(snap).join('\n====\n')
		await generate(root)
		const after = ['.swelte/routes.js', '.swelte/ssr-manifest.json', '.swelte/entry-main.ts', '.swelte/routes/server_gen.v'].map(snap).join('\n====\n')
		assert.equal(after, before)
	})
})
