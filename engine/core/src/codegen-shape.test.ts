function goldenFn(over: Partial<RpcFnGolden> = {}): RpcFnGolden {
	return {
		name: 'get_greeting',
		attr: 'get',
		qualifier: undefined,
		params: [],
		vret: 'string',
		tsret: 'string',
		fallible: false,
		singleArgsStruct: undefined,
		...over,
	}
}

