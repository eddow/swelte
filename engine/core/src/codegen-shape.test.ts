async function generate(root: string, opts: Record<string, unknown> = {}): Promise<void> {
	const { swelte } = await import('./vite.js')
	const plug = swelte(opts) as unknown as {
		configResolved?: (c: { root: string }) => void
		buildStart?: () => Promise<void>
	}
	plug.configResolved?.({ root })
	await plug.buildStart?.()
}

function tree(root: string, dir: string): string[] {
	const out: string[] = []
	const walk = (d: string, rel: string) => {
		for (const e of readdirSync(d).sort()) {
			const p = join(d, e)
			if (statSync(p).isDirectory()) walk(p, rel + e + '/')
			else out.push(rel + e)
		}
	}
	walk(join(root, dir), '')
	return out
}

